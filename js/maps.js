const SOLID_TILES = new Set([1, 2, 7]);

// String maps: '#' wall, '.' floor, 'D' door
function parseMap(rows, floor = 9) {
    const lookup = { '#': 1, '.': floor, 'D': 4, 'T': 2, ',': 3, 'H': 7, 'B': 8 };
    return rows.map(r => [...r].map(ch => lookup[ch] !== undefined ? lookup[ch] : floor));
}

